"""Build the launcher icon from the current Vibe face; requires Pillow only.

Writes editable SVG, a PNG preview, and an uncompressed LVGL RGB565 image.
RGB565 matches the factory launcher assets and needs no alpha decompression.
"""
import math
import struct
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SIZE = 200
SCALE = 4
BACKGROUND = "#000000"
BODY = "#05080D"
TRACK = "#202832"
WEEK = "#74E3F3"
FIVE = "#FFBB68"
SHARED = "#B39AFF"
EYES = "#83C9F4"


def main():
    image = Image.new("RGB", (SIZE * SCALE, SIZE * SCALE), BACKGROUND)
    draw = ImageDraw.Draw(image)
    svg = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200">',
           '<title>Vibe — quota rings and companion eyes</title>',
           '<rect width="200" height="200" fill="#000000"/>',
           f'<circle cx="100" cy="100" r="96" fill="{BODY}"/>']
    draw.ellipse((4*SCALE, 4*SCALE, 196*SCALE, 196*SCALE), fill=BODY)

    def band(radius, start, end, width, color):
        # Filled annular sectors keep flat joins, exactly as the device face.
        steps = max(2, math.ceil((end - start) * 2))
        angles = [math.radians(start + (end - start) * i / steps) for i in range(steps + 1)]
        points = [(100 + r*math.cos(a), 100 + r*math.sin(a))
                  for r, values in ((radius + width/2, angles),
                                    (radius - width/2, reversed(angles))) for a in values]
        draw.polygon([(round(x*SCALE), round(y*SCALE)) for x, y in points], fill=color)
        path = "M " + " L ".join(f"{x:.3f} {y:.3f}" for x, y in points) + " Z"
        svg.append(f'<path d="{path}" fill="{color}"/>')

    band(85, 0, 360, 12, TRACK)
    # Fixed brand proportions, not live or default quota readings.
    band(88.5, 90, 230, 5, WEEK)
    band(81.5, 90, 180, 5, FIVE)
    band(85, 290, 450, 12, SHARED)

    def rounded_rect(x, y, w, h, radius, color):
        draw.rounded_rectangle((x*SCALE, y*SCALE, (x+w)*SCALE, (y+h)*SCALE),
                               radius=radius*SCALE, fill=color)
        svg.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" '
                   f'rx="{radius}" fill="{color}"/>')

    for x in (69, 113):
        rounded_rect(x, 77, 18, 34, 9, EYES)
        rounded_rect(x+5, 82, 4, 7, 2, "#DBF5FF")
    svg.append('</svg>')
    brand = ROOT / "assets/brand"
    (brand / "vibe-icon.svg").write_text("\n".join(svg) + "\n", encoding="utf-8")
    image.save(brand / "vibe-icon.png")
    image = image.resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    image.save(brand / "vibe-icon-200.png")
    pixels = image.tobytes()
    raw = bytearray()
    for offset in range(0, len(pixels), 3):
        r, g, b = pixels[offset:offset+3]
        raw.extend(struct.pack("<H", ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)))
    assert len(raw) == SIZE * SIZE * 2
    rows = ["    " + ", ".join(f"0x{x:02x}" for x in raw[i:i+16]) + ","
            for i in range(0, len(raw), 16)]
    output = '''// SPDX-License-Identifier: MIT
// Generated by scripts/build-vibe-icon.py from the current Vibe face.
// Uncompressed RGB565, matching factory launcher assets.
#include <lvgl.h>
static const LV_ATTRIBUTE_MEM_ALIGN uint8_t icon_vibe_map[] = {
''' + "\n".join(rows) + '''
};
const lv_image_dsc_t icon_vibe = {
    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,
               .w = 200, .h = 200, .stride = 400},
    .data_size = sizeof(icon_vibe_map), .data = icon_vibe_map,
};
'''
    (ROOT / "main/assets/vibe/icon_vibe.c").write_text(output, encoding="utf-8")
    print(f"Vibe icon: {SIZE}x{SIZE}, {len(raw)} bytes, RGB565 without compression")


if __name__ == "__main__":
    main()
