"""Convert the generated Vibe PNG to a 200px LVGL RGB565A8/LZ4 asset.

Run from the repository root with Pillow and lz4 installed.
The source PNG is preserved; only resizing and pixel-format conversion occur.
"""
from pathlib import Path
import struct

import lz4.block
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def main():
    image = Image.open(ROOT / "assets/brand/vibe-logo-dark.png").convert("RGBA")
    if image.getextrema()[3][0] != 0:
        raise ValueError("Logo must have transparent pixels")
    image = image.resize((200, 200), Image.Resampling.LANCZOS)
    color, alpha = bytearray(), bytearray()
    pixels = image.tobytes()
    for offset in range(0, len(pixels), 4):
        r, g, b, a = pixels[offset:offset + 4]
        color.extend(struct.pack("<H", ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)))
        alpha.append(a)
    raw = bytes(color + alpha)
    compressed = lz4.block.compress(raw, store_size=False)
    assert lz4.block.decompress(compressed, uncompressed_size=len(raw)) == raw
    packed = struct.pack("<III", 2, len(compressed), len(raw)) + compressed
    rows = ["    " + ", ".join(f"0x{x:02x}" for x in packed[i:i+16]) + ","
            for i in range(0, len(packed), 16)]
    output = '''// SPDX-License-Identifier: MIT
// Vibe logo generated with OpenAI image generation; see assets/brand/README.md.
// Generated by scripts/build-vibe-icon.py; RGB565A8 with LVGL LZ4 compression.
#include <lvgl.h>
static const LV_ATTRIBUTE_MEM_ALIGN uint8_t icon_vibe_map[] = {
''' + "\n".join(rows) + '''
};
const lv_image_dsc_t icon_vibe = {
    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8,
               .flags = LV_IMAGE_FLAGS_COMPRESSED, .w = 200, .h = 200, .stride = 400},
    .data_size = sizeof(icon_vibe_map), .data = icon_vibe_map,
};
'''
    target = ROOT / "main/assets/vibe/icon_vibe.c"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(output, encoding="utf-8")
    print(f"Vibe icon: {len(raw)} -> {len(packed)} bytes; LZ4 roundtrip verified")


if __name__ == "__main__":
    main()
